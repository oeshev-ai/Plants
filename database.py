"""SQLite storage and plant lookup (case-insensitive, partial names)."""

from __future__ import annotations

import os
import sqlite3
from dataclasses import dataclass
from pathlib import Path

DB_PATH = Path(__file__).resolve().parent / "plants.db"


@dataclass(frozen=True)
class Plant:
    name: str
    light: str
    water: str
    temperature: str
    repot: str


def _py_lower(s: str | None) -> str:
    return (s or "").lower()


def _connect() -> sqlite3.Connection:
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.create_function("py_lower", 1, _py_lower)
    return conn


def init_db() -> None:
    rows = _seed_rows()
    with _connect() as conn:
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS plants (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                name TEXT NOT NULL UNIQUE,
                light TEXT NOT NULL,
                water TEXT NOT NULL,
                temperature TEXT NOT NULL,
                repot TEXT NOT NULL
            )
            """
        )
        # Full re-seed so edits to _seed_rows() always apply (no stale rows).
        conn.execute("DELETE FROM plants")
        conn.executemany(
            """
            INSERT INTO plants (name, light, water, temperature, repot)
            VALUES (?, ?, ?, ?, ?)
            """,
            rows,
        )


def find_plant(user_text: str) -> Plant | None:
    q = (user_text or "").strip()
    if not q:
        return None
    ql = q.lower()

    with _connect() as conn:
        # 1) exact case-insensitive
        row = conn.execute(
            "SELECT name, light, water, temperature, repot FROM plants WHERE py_lower(name) = ?",
            (ql,),
        ).fetchone()
        if row:
            return Plant(**dict(row))

        # 2) name starts with query (e.g. "монстера" -> "Монстера делициоза")
        rows = conn.execute(
            """
            SELECT name, light, water, temperature, repot
            FROM plants
            WHERE py_lower(name) LIKE ? || '%'
            ORDER BY length(name) ASC, name ASC
            """,
            (ql,),
        ).fetchall()
        if rows:
            r = rows[0]
            return Plant(**dict(r))

        # 3) contains (e.g. "потос" -> "Эпипремнум (Потос)")
        row = conn.execute(
            """
            SELECT name, light, water, temperature, repot
            FROM plants
            WHERE py_lower(name) LIKE '%' || ? || '%'
            ORDER BY length(name) ASC, name ASC
            LIMIT 1
            """,
            (ql,),
        ).fetchone()
        if row:
            return Plant(**dict(row))

    return None


